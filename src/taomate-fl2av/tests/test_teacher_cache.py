"""CPU-only production teacher-cache roundtrip and extracted-global smoke tests."""
import builtins
import json
import pickle
from pathlib import Path
import symtable
import tempfile
import unittest

from digitalhuman_h3.inference import base10_hiar as teacher
from digitalhuman_h3.streaming.geometry import plan_native_stream


class TensorStub:
    def __init__(self, value, shape):
        self.value = value
        self.shape = shape

    def detach(self):
        return self

    def to(self, **kwargs):
        return self


class TorchStub:
    float32 = "float32"

    @staticmethod
    def save(value, path):
        with Path(path).open("wb") as stream:
            pickle.dump(value, stream)

    @staticmethod
    def load(path, **kwargs):
        with Path(path).open("rb") as stream:
            return pickle.load(stream)


class TeacherCacheTest(unittest.TestCase):
    def test_production_format_cache_roundtrip(self):
        plan = plan_native_stream(124)
        end = plan.phases[-1]
        request = teacher.Base10HiARRequest(
            index=0, prompt="seated_001 teacher cache smoke", seed=9301,
            phase_start=0, phase_stop=len(plan.phases), frame_start=0, frame_stop=124,
            video_latent_start=0, video_latent_stop=end.video_latent_stop,
            audio_latent_start=0, audio_latent_stop=end.audio_latent_stop,
        )
        schedule = teacher.Base10HiARSchedule(plan, (request,))
        geometry = teacher.base10_teacher_geometry(
            width=768, height=1376, video_latent_h=86, video_latent_w=48,
        )
        visual = {"task": "ii2va", "end_frame": 124,
                  "end_video_latent": end.video_latent_stop,
                  "tail_visibility": "last_request_only"}
        with tempfile.TemporaryDirectory(prefix="h3-teacher-cache-test-") as temporary:
            root = Path(temporary)
            teacher.write_base10_teacher_request(
                TorchStub, root=root, request=request,
                milestones={i: TensorStub(i, (2 * request.audio_latent_count, 32))
                            for i in range(3)},
                teacher_receipt={"visual_conditioning": visual,
                                 "conditioned_forward_count": 9,
                                 "audio_noise_seed": 9301},
                producer_geometry=geometry,
            )
            marker = {
                "schema": "digitalhuman_h3.inference.base10_hiar_teacher_set.v1",
                "case_id": "seated_001", "request_count": 1,
                "base_precision": "bf16", "producer_geometry": geometry,
                "producer_topology": teacher.base10_keyframe_teacher_producer_topology(),
                "strategy": teacher.BASE10_KEYFRAME_STRATEGY,
                "partition": "fl2va", "visual_conditioning": visual,
                "audio_noise_seed_sequence": [9301],
            }
            (root / "complete.json").write_text(json.dumps(marker), encoding="utf-8")
            artifact = teacher.CompletedBase10TeacherArtifact.open(
                root, case_id="seated_001", schedule=schedule,
                consumer_geometry=geometry, visual_conditioning=visual,
            )
            loaded = artifact.load_request(TorchStub, request_index=0, device="cpu")
            self.assertEqual([loaded["milestones"][i].value for i in range(3)], [0, 1, 2])
            self.assertEqual(loaded["receipt"]["audio_latents_per_channel"], 207)
            self.assertEqual(loaded["receipt"]["conditioned_forward_count"], 9)
            # A different duration changes the whole-clip endpoint even at
            # the same spatial geometry, prompt and seed.
            with self.assertRaisesRegex(RuntimeError, "visual conditions or endpoint differ"):
                teacher.CompletedBase10TeacherArtifact.open(
                    root, case_id="seated_001", schedule=schedule,
                    consumer_geometry=geometry,
                    visual_conditioning=dict(visual, end_frame=260, end_video_latent=77),
                )

    def test_extracted_native_globals_are_defined(self):
        # Detect missing same-module helpers before loading the large model.
        native_root = Path(teacher.__file__).resolve().parents[1]
        builtin_names = set(dir(builtins)) | {
            "__file__", "__name__", "__package__", "__spec__",
            "__conditional_annotations__",  # Generated by Python 3.14.
        }

        def unresolved(table, bound):
            names = {symbol.get_name() for symbol in table.get_symbols()
                     if symbol.is_global() and symbol.is_referenced()
                     and symbol.get_name() not in bound}
            for child in table.get_children():
                names.update(unresolved(child, bound))
            return names

        failures = {}
        for path in native_root.rglob("*.py"):
            table = symtable.symtable(path.read_text(), str(path), "exec")
            bound = builtin_names | {
                symbol.get_name() for symbol in table.get_symbols()
                if symbol.is_assigned() or symbol.is_imported() or symbol.is_namespace()
            }
            missing = unresolved(table, bound)
            if missing:
                failures[str(path.relative_to(native_root))] = sorted(missing)
        self.assertEqual(failures, {})


if __name__ == "__main__":
    unittest.main()
